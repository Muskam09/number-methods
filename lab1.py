import math

print("=== Завдання а) Визначення точнішої рівності ===")
# 1. Для першої рівності (7/22 = 0.318)
a_approx = 0.318
a_exact = 7 / 22
delta_a = abs(a_exact - a_approx)
delta_rel_a = delta_a / abs(a_approx)

# 2. Для другої рівності (sqrt(13) = 3.61)
b_approx = 3.61
b_exact = math.sqrt(13)
delta_b = abs(b_exact - b_approx)
delta_rel_b = delta_b / abs(b_approx)

print(f"Рівність a (7/22 = 0.318):")
print(f"  Точне значення: {a_exact:.6f}")
print(f"  Абсолютна похибка: {delta_a:.6f}")
print(f"  Відносна похибка: {delta_rel_a:.6f}")

print(f"\nРівність b (sqrt(13) = 3.61):")
print(f"  Точне значення: {b_exact:.6f}")
print(f"  Абсолютна похибка: {delta_b:.6f}")
print(f"  Відносна похибка: {delta_rel_b:.6f}")

if delta_rel_a < delta_rel_b:
    print("\nВисновок: Рівність 7/22 = 0.318 є точнішою, оскільки її відносна похибка менша.")
else:
    print("\nВисновок: Рівність sqrt(13) = 3.61 є точнішою, оскільки її відносна похибка менша.")

print("\n=== Завдання б) Округлення сумнівних цифр ===")
c_approx = 0.3944
delta_rel_c = 0.0015  # 0.15% у десятковому вигляді

# Визначаємо абсолютну похибку
delta_c = c_approx * delta_rel_c

print(f"Початкове число: {c_approx}")
print(f"Абсолютна похибка: {delta_c:.7f}")

# Оскільки абсолютна похибка становить ~0.00059, правильними є десяті та соті.
# Тисячні долі вже сумнівні, тому округлюємо число до 3 знаків після коми (до тисячних).
c_rounded = round(c_approx, 3)
print(f"Округлене число з правильними знаками: {c_rounded}")

print("\n=== Завдання в) Граничні похибки правильного числа ===")
f_approx = 21.7

# Оскільки всі цифри за замовчуванням правильні, гранична абсолютна похибка
# не перевищує одиниці останнього залишеного розряду (десятих).
delta_f = 0.1 

# Обчислюємо граничну відносну похибку
delta_rel_f = delta_f / f_approx

print(f"Число: {f_approx}")
print(f"Гранична абсолютна похибка: {delta_f}")
print(f"Гранична відносна похибка: {delta_rel_f:.6f} (або {delta_rel_f * 100:.2f}%)")